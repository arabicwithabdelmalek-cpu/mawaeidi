const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
require("../schedule-time.js");
require("../lesson-model.js");
const app=fs.readFileSync(path.join(__dirname,"../app-main.js"),"utf8");
require("../session-state.js");
const update=global.MawaeidiSessionState.lessonWithSessionStatus;
const initial={id:"lesson-a",schedules:[{day:"الأربعاء",time:"10:00"}],sessionRecords:[{id:"base-a",kind:"base",date:"2026-11-25",time:"10:00",status:"default",note:"ملاحظة من الموقع",updatedAt:"2026-11-25T10:00:00Z"}]};
const ctx={kind:"base",date:"2026-11-25",time:"10:00"};
let result=update(initial,ctx,"completed","","","ملاحظة من الموقع");
assert.equal(result.sessionRecords[0].note,"ملاحظة من الموقع");
result=update(result,ctx,"automatic","","","ملاحظة من الموقع");
assert.equal(result.sessionRecords[0].status,"default");
assert.equal(result.sessionRecords[0].note,"ملاحظة من الموقع");
result=update(result,ctx,"rescheduled","2026-11-26","11:00","سبب التأجيل");
assert.equal(result.sessionRecords[0].note,"سبب التأجيل");
const replacementId=result.sessionRecords.find(r=>r.kind==="replacement").id;
const replacement={kind:"replacement",recordId:replacementId};
result=update(result,replacement,"completed","","","ملاحظة البديل");
assert.equal(result.sessionRecords.find(r=>r.kind==="replacement").note,"ملاحظة البديل");
result=update(result,ctx,"rescheduled","2026-11-27","11:00","سبب التأجيل");
assert.equal(result.sessionRecords.find(r=>r.kind==="replacement").note,"ملاحظة البديل");
assert.equal(result.sessionRecords.find(r=>r.kind==="replacement").date,"2026-11-27");
assert.match(app,/id="sessionNote"/);
assert.match(app,/esc\(occurrence\.record\?\.note\|\|""\)/);
assert.match(app,/lessonWithSessionStatus\(lessons\[index\],context,status,newDate,newTime,note\)/);
assert.match(app,/const MAX_SESSION_NOTE_LENGTH=1000/);
assert.match(fs.readFileSync(path.join(__dirname,"../scripts/prepare-mobile.mjs"),"utf8"),/"lesson-model\.js"/);
console.log("Android session note editing, normalization, status reset, rescheduling and replacement note retention passed.");
