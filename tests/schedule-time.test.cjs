const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
require("../schedule-time.js");
const t=global.MawaeidiScheduleTime;
assert.equal(t.validTimeZone("Africa/Cairo"),true);
assert.equal(t.validTimeZone("No/Such_Zone"),false);
assert.equal(t.validDateKey("2024-02-29"),true);
assert.equal(t.validDateKey("2026-02-29"),false);
assert.equal(t.validDateKey(null),false);
assert.equal(t.mins("23:59"),1439);
assert.equal(t.mins("24:00"),0);
assert.equal(t.fmt("00:05"),"12:05 ص");
assert.equal(t.fmt("13:30"),"1:30 م");
assert.equal(t.wallTimeToInstant("2026-01-15","12:00").toISOString(),"2026-01-15T10:00:00.000Z");
assert.equal(t.wallTimeToInstant("2026-07-15","12:00").toISOString(),"2026-07-15T09:00:00.000Z");
assert.equal(t.wallTimeToInstant("2026-01-15","25:00"),null);
assert.equal(t.wallTimeToInstant("2026-02-30","10:00"),null);
assert.equal(t.zoneOffsetMinutes(new Date("2026-01-15T10:00:00Z"),"Asia/Kolkata"),330);
const late=new Date("2026-01-15T22:30:00Z");
assert.equal(t.currentDateKey(late),"2026-01-16");
assert.equal(t.currentTimeKey(late),"00:30");
assert.equal(t.dateKeyInZone(late,"Asia/Baku"),"2026-01-16");
assert.equal(t.timeKeyInZone(late,"Asia/Baku"),"02:30");
assert.equal(t.formattedTimeInZone(late,"Asia/Baku"),"2:30 ص");
assert.equal(t.dayShiftLabel("2026-01-15","2026-01-16")," · اليوم التالي");
assert.equal(t.addDaysToDateKey("2024-02-28",1),"2024-02-29");
assert.equal(t.addDaysToDateKey("2026-12-31",1),"2027-01-01");
assert.equal(t.dayNameForDateKey("2026-11-25"),"الأربعاء");
const occurrence={date:"2026-11-25",time:"10:00",lesson:{duration:45}};
assert.equal(t.occurrenceHasStarted(occurrence,"2026-11-25","09:59"),false);
assert.equal(t.occurrenceHasStarted(occurrence,"2026-11-25","10:00"),true);
assert.equal(t.occurrenceHasEnded(occurrence,"2026-11-25","10:44"),false);
assert.equal(t.occurrenceHasEnded(occurrence,"2026-11-25","10:45"),true);
assert.equal(t.occurrenceHasEnded(occurrence,"2026-11-26","00:00"),true);
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const app=read("app-main.js"),html=read("index.html"),sw=read("sw.js");
for(const name of Object.keys(t))assert.ok(app.includes("function "+name+"(...args){return window.MawaeidiScheduleTime."+name+"(...args)}"),name);
const src=html.match(/src="(\.\/schedule-time\.js\?v=\d+)"/)?.[1];
assert.ok(src&&html.indexOf(src)<html.indexOf("./app-main.js?v="));
assert.ok(sw.includes(JSON.stringify(src)));
assert.doesNotThrow(()=>new Function(app));
console.log("Shared schedule time: validation, Cairo winter/summer, date boundary, formatting and session state passed.");
