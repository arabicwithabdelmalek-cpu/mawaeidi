const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
require("../schedule-time.js");
require("../lesson-model.js");
const model=global.MawaeidiLessonModel;
const timestamp="2026-11-25T10:00:00.000Z";
const base={id:"lesson-a",name:"Arabic",duration:45,schedules:[{day:"الأربعاء",time:"10:00"},{day:"invalid",time:"10:00"},{day:"الأربعاء",time:"25:00"}],studentTimeZone:"Asia/Baku",reminderLeads:[15,60,15,10,5,999],sessionRecords:[{id:"note-only",kind:"base",date:"2026-11-25",time:"10:00",status:"default",note:" مراجعة الدرس ",updatedAt:timestamp},{id:"base-rescheduled",kind:"base",date:"2026-12-02",time:"10:00",status:"rescheduled",replacementId:"replacement-a",note:"سبب التأجيل",updatedAt:timestamp},{id:"replacement-a",kind:"replacement",date:"2026-12-03",time:"10:00",status:"default",sourceDate:"2026-12-02",sourceTime:"10:00",note:"موعد بديل",updatedAt:timestamp},{id:"orphan",kind:"replacement",date:"2026-12-03",time:"11:00",sourceDate:"2026-12-02",sourceTime:"11:00",updatedAt:timestamp}]};
const normalized=model.normalizeLesson(base);
assert.equal(normalized.duration,45);
assert.equal(normalized.studentTimeZone,"Asia/Baku");
assert.deepEqual(normalized.schedules,[{day:"الأربعاء",time:"10:00"}]);
assert.deepEqual(normalized.reminderLeads,[60,15,10]);
assert.deepEqual(normalized.sessionRecords.map(r=>r.note),["مراجعة الدرس","سبب التأجيل","موعد بديل"]);
assert.deepEqual(model.normalizeLesson(normalized),normalized);
assert.equal(model.normalizeLesson({...base,duration:2,studentTimeZone:"invalid"}).duration,60);
assert.equal(model.normalizeLesson({...base,studentTimeZone:"invalid"}).studentTimeZone,"");
assert.deepEqual(model.normalizeNotificationLeads([]),[60,15]);
assert.equal(model.validNotificationLead(999),15);
assert.equal(model.normalizeSessionRecords([{kind:"base",date:"2026-11-25",time:"10:00",status:"default"}]).length,0);
assert.equal(model.normalizeSessionRecords([{kind:"base",date:"2026-11-25",time:"10:00",note:"x".repeat(1500)}])[0].note.length,1000);
const dup=model.normalizeLessons([base,base]);assert.equal(new Set(dup.map(x=>x.id)).size,2);
assert.deepEqual(model.parseScheduleBackupObject({format:"mawaeidi-schedule",version:1,lessons:[base]}),[normalized]);
assert.throws(()=>model.parseScheduleBackupObject([{id:"a",schedules:[]}]),/invalid_schedule/);
assert.throws(()=>model.parseScheduleBackupObject({format:"wrong",lessons:[]}),/invalid_schedule_backup/);
const merged=model.mergeBackupLessons([normalized],[{...normalized,name:"Updated"},{...normalized,id:"lesson-b"}]);
assert.equal(merged.added,1);assert.equal(merged.updated,1);assert.equal(merged.lessons[0].name,"Updated");
assert.deepEqual(merged.lessons[0].sessionRecords,normalized.sessionRecords);
assert.equal(base.name,"Arabic");
const read=p=>fs.readFileSync(path.join(__dirname,"..",p),"utf8");
const app=read("app-main.js"),html=read("index.html"),sw=read("sw.js");
for(const name of Object.keys(model))assert.ok(app.includes("function "+name+"(...args){return window.MawaeidiLessonModel."+name+"(...args)}"),name);
const src=html.match(/src="(\.\/lesson-model\.js\?v=\d+)"/)?.[1];
assert.ok(src&&html.indexOf("schedule-time.js?v=")<html.indexOf(src)&&html.indexOf(src)<html.indexOf("./app-main.js?v="));
assert.ok(sw.includes(JSON.stringify(src)));
assert.doesNotThrow(()=>new Function(app));
console.log("Shared lesson model: normalization, notes, linked replacements, backup merge and asset wiring passed.");
