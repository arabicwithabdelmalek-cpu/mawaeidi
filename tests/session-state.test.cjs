const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
require("../schedule-time.js");require("../lesson-model.js");require("../session-state.js");
const s=global.MawaeidiSessionState;
const initial={id:"lesson-a",name:"Arabic",duration:45,schedules:[{day:"الأربعاء",time:"10:00"}],sessionRecords:[]};
const ctx={kind:"base",date:"2026-11-25",time:"10:00"};
let lesson=s.lessonWithSessionStatus(initial,ctx,"automatic","","","ملاحظة");
assert.equal(lesson.sessionRecords[0].note,"ملاحظة");
assert.equal(s.baseSessionRecord(lesson,ctx.date,ctx.time).status,"default");
lesson=s.lessonWithSessionStatus(lesson,ctx,"rescheduled","2026-11-26","11:00","سبب التأجيل");
const id=lesson.sessionRecords.find(x=>x.kind==="replacement").id;
assert.equal(s.datedOccurrencesForDate("2026-11-25",[lesson])[0].record.status,"rescheduled");
assert.equal(s.datedOccurrencesForDate("2026-11-26",[lesson])[0].kind,"replacement");
lesson=s.lessonWithSessionStatus(lesson,{kind:"replacement",recordId:id},"completed","","","ملاحظة البديل");
lesson=s.lessonWithSessionStatus(lesson,ctx,"rescheduled","2026-11-27","12:00","سبب التأجيل");
assert.equal(s.replacementSessionRecord(lesson,id).note,"ملاحظة البديل");
assert.equal(s.replacementSessionRecord(lesson,id).date,"2026-11-27");
assert.equal(s.datedOccurrencesForDate("2026-11-26",[lesson]).length,0);
assert.equal(s.datedOccurrencesForDate("2026-11-27",[lesson])[0].recordId,id);
assert.equal(s.occurrenceStatus({record:{status:"cancelled_unpaid"}}),"cancelled_unpaid");
assert.equal(s.occurrenceIsInactive({record:{status:"cancelled_unpaid"}}),true);
assert.equal(s.sessionStatusInfo("free").className,"free");
assert.equal(s.occurrenceRawStatus({}),"default");
assert.deepEqual(s.datedOccurrencesForDate("invalid",[lesson]),[]);
assert.deepEqual(initial.sessionRecords,[]);
const read=p=>fs.readFileSync(path.resolve(__dirname,"..",p),"utf8");
const app=read("app-main.js"),html=read("index.html"),sw=read("sw.js");
for(const name of Object.keys(s))assert.ok(app.includes("window.MawaeidiSessionState."+name+"("),name);
const src=html.match(/src="(\.\/session-state\.js\?v=\d+)"/)?.[1];
assert.ok(src&&html.indexOf("lesson-model.js?v=")<html.indexOf(src)&&html.indexOf(src)<html.indexOf("./app-main.js?v="));
assert.ok(sw.includes(JSON.stringify(src)));
assert.doesNotThrow(()=>new Function(app));
console.log("Shared session state: status, rescheduling, replacement note retention and dated occurrences passed.");
