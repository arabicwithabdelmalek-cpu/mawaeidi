const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
require("../schedule-time.js");require("../world-clock-model.js");
const w=global.MawaeidiWorldClockModel;
const winter=new Date("2026-01-15T12:00:00Z"),summer=new Date("2026-07-15T12:00:00Z");
assert.equal(w.utcOffsetText(winter,"Africa/Cairo"),"UTC+2");
assert.equal(w.utcOffsetText(summer,"Africa/Cairo"),"UTC+3");
assert.equal(w.utcOffsetText(winter,"Asia/Kolkata"),"UTC+5:30");
assert.equal(w.worldDifferenceText(winter,"Africa/Cairo","Asia/Kolkata"),"التوقيت الثاني أمام بـ 3:30");
assert.equal(w.worldDifferenceText(winter,"Asia/Kolkata","Africa/Cairo"),"التوقيت الثاني متأخر بـ 3:30");
assert.equal(w.worldDifferenceText(winter,"Africa/Cairo","Africa/Cairo"),"نفس التوقيت");
assert.equal(w.worldOffsetText(winter,"Africa/Cairo","Asia/Baku"),"−2 عن "+w.timeZoneShortLabel("Asia/Baku"));
assert.equal(w.worldHour12Label(0),"12 ص");assert.equal(w.worldHour12Label(12),"12 م");assert.equal(w.worldHour12Label(-1),"11 م");
assert.equal(w.worldClockState(8).className,"work");assert.equal(w.worldClockState(18).className,"evening");assert.equal(w.worldClockState(23).className,"night");
assert.equal(w.worldCityArabicName("Cairo"),"القاهرة");assert.equal(w.worldCityArabicName("","Asia/Baku"),"باكو");
assert.equal(w.normalizeZoneSearch("إِسطنبول"),"اسطنبول");
assert.equal(w.normalizeZoneSearch("أُذْرَبَيْجَان"),"اذربيجان");
assert.equal(w.normalizeZoneSearch("آسيا"),"اسيا");
assert.equal(w.normalizeZoneSearch("São Paulo"),"sao paulo");
assert.equal(w.resolveTimeZoneText("Africa/Cairo").entry.zone,"Africa/Cairo");
assert.equal(w.resolveTimeZoneText("asia/baku").entry.zone,"Asia/Baku");
assert.equal(w.resolveTimeZoneText("zzzzzzzz-no-matching-zone").entry,null);
const catalog=w.timeZoneCatalog();
assert.ok(catalog.length>100);assert.equal(new Set(catalog.map(x=>x.zone)).size,catalog.length);
assert.strictEqual(w.timeZoneCatalog(),catalog);
const egypt=w.timeZoneEntry("Africa/Cairo");assert.equal(egypt.code,"EG");
assert.equal(w.resolveTimeZoneText(egypt.label).entry.zone,"Africa/Cairo");
assert.equal(w.resolveTimeZoneText(egypt.country).entry.zone,"Africa/Cairo");
assert.equal(w.worldFlagEmoji("EG"),"🇪🇬");assert.equal(w.worldFlagEmoji("xxx"),"🌐");
const read=p=>fs.readFileSync(path.resolve(__dirname,"..",p),"utf8");
const app=read("app-main.js"),html=read("index.html"),sw=read("sw.js");
for(const name of Object.keys(w))assert.ok(app.includes("window.MawaeidiWorldClockModel."+name+"("),name);
assert.ok(!app.includes("const TIMEZONE_COUNTRY_MAP="));
const src=html.match(/src="(\.\/world-clock-model\.js\?v=\d+)"/)?.[1];
assert.ok(src&&html.indexOf("schedule-time.js?v=")<html.indexOf(src)&&html.indexOf(src)<html.indexOf("./app-main.js?v="));
assert.ok(sw.includes(JSON.stringify(src)));
assert.match(app,/function worldOffsetText\(date,zone,baseZone=savedWorldClockBase\(\)\)/);
assert.doesNotThrow(()=>new Function(app));
console.log("Shared world clock model: seasonal offsets, fractional zones, Arabic search, catalog and wiring passed.");
